#!/usr/bin/env python3
"""Step 8: write docs/SUMMARY.md from paper/stats.json.

Plain-language note: every number in the summary page is copied here from the file
the pipeline writes, never typed by hand, so text and data cannot disagree. Re-run
after any change.
"""

import json

from common import PAPER, ROOT


def main():
    s = json.loads((PAPER / "stats.json").read_text())
    f = lambda x: f"{x:,}"
    cm = s["coding_mode_counts"]
    tr = s["coding_trigger_counts"]
    rows = [("Coal, underground", "coal_underground"), ("Coal, surface", "coal_surface"),
            ("Metal/nonmetal, underground", "metal_nonmetal_underground"),
            ("Metal/nonmetal, surface", "metal_nonmetal_surface")]
    t = "\n".join(
        f"| {lab} | {f(s[f'injuries_{k}_2000_2025'])} | {s[f'fatal_{k}_2000_2025']} | "
        f"{s[f'rate_{k}_2000']:.3f} | {s[f'rate_{k}_2025']:.3f} |" for lab, k in rows)
    modes = "\n".join(f"| {k.replace('_', ' ')} | {v} |" for k, v in
                      sorted(cm.items(), key=lambda x: -x[1]))
    md = f"""# GroundFall-US: summary of results

*DRAFT, not yet verified by the authors. Generated by code/08_summary.py from paper/stats.json; do not edit by hand.*

## The dataset

- **{f(s['n_ground_failure_records'])}** ground-failure records at U.S. mines, {s['year_first']} to {s['year_last']} (2026 partial), selected by MSHA classification "fall of roof or back" or "fall of face/rib/pillar/side/highwall".
- Of these, **{f(s['n_ground_failure_injury'])}** injured someone (MSHA degrees 01 to 06), **{s['n_ground_failure_fatal']}** were fatal, and **{f(s['n_ground_failure_no_injury'])}** were reportable falls in which nobody was hurt.
- **{s['qa_mine_match_pct']}%** of records matched the MSHA Mines file and **{s['qa_hours_match_pct']}%** matched hours worked for the same mine, subunit, and year.

## Injury rates per 200,000 hours (mine-operator employees, contractors excluded)

| Sector and mine type | Injuries 2000-2025 | Deaths 2000-2025 | Rate 2000 | Rate 2025 |
|---|---|---|---|---|
{t}

## Failure modes, surface metal/nonmetal ({s['coding_n']} narratives, rules v{s['coding_rules_version']}, not yet validated)

| Failure mode | Records |
|---|---|
{modes}

Triggers named in the narrative: blasting {tr['blasting']}, water {tr['water']}, scaling {tr['scaling']}.
"""
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "SUMMARY.md").write_text(md)
    print("Wrote docs/SUMMARY.md")


if __name__ == "__main__":
    main()
